NEW_AXES = {
    "chemical": {"name": "化工周期", },
    "infra": {"name": "基建地产", },
}


def main() -> None:
    d = yaml.safe_load(AXIS.read_text(encoding="utf-8"))
    axes = d["axes"]
    by_key = {a["key"]: a for a in axes}
    before = sum(len(a.get("match") or []) for a in axes)

    # 新增板块
    for k, meta in NEW_AXES.items():
        if k not in by_key:
            axes.append({"key": k, "name": meta["name"], "match": []})
            by_key[k] = axes[-1]

    added_n = 0
    for key, tags in ADD.items():
        if key not in by_key:
            print(f"⚠ 板块 {key} 不存在，跳过")
            continue
        cur = by_key[key].setdefault("match", [])
        cur_set = set(str(x) for x in cur)
        for t in tags:
            if t not in cur_set:
                cur.append(t)
                cur_set.add(t)
                added_n += 1

    after = sum(len(a.get("match") or []) for a in axes)
    d["version"] = 3
    d["generated_from"] = ("2026-10-08~2026-11-20 真实题材标签全量诊断"
                           "（938 只涨停股 / 2196 个唯一标签）+ 人工精选归并")
    d.setdefault("changelog", []).append({
        "v3": (f"2026-11-23 扩轴：板块 9→{len(axes)}，标签 {before}→{after}（+{added_n}）。"
               "起因：实测 46.7% 的涨停股有真实题材标签但轴未收录，"
               "导致悟空真经凑不齐龟兔配对而漏票。"
               "本次只补语义明确的题材标签，排除业绩(三季报/业绩预增)与"
               "属性(国资/回购/股权转让)类——后者不应参与题材分组。")
    })

    AXIS.write_text(yaml.dump(d, allow_unicode=True, sort_keys=False,
                              default_flow_style=False, width=200),
                    encoding="utf-8")
    print(f"板块 {len(axes)} 个，标签 {before} → {after}（新增 {added_n}）")
    for a in axes:
        print(f"  {a['key']:<14} {a['name']:<10} {len(a.get('match') or []):>4}")


if __name__ == "__main__":
    main()
